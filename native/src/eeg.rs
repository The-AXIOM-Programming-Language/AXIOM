//! Core EEG domain types for AXIOM.
//!
//! This module models metadata and channel-major samples only. It does not
//! perform filtering, resampling, file I/O, or source localization.

#[derive(Debug, Clone, Copy, PartialEq)]
pub struct SamplingRate {
    hz: f64,
}

impl SamplingRate {
    pub fn new(hz: f64) -> Result<Self, EegError> {
        if !hz.is_finite() || hz <= 0.0 {
            return Err(EegError::InvalidSamplingRate(hz));
        }
        Ok(Self { hz })
    }

    pub fn hz(self) -> f64 {
        self.hz
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum VoltageUnit {
    Volt,
    Millivolt,
    Microvolt,
}

impl VoltageUnit {
    /// Return the multiplier that converts this unit to volts.
    pub fn to_volts_scale(self) -> f64 {
        match self {
            Self::Volt => 1.0,
            Self::Millivolt => 1e-3,
            Self::Microvolt => 1e-6,
        }
    }
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum ChannelReference {
    /// The acquisition reference was not supplied or is unknown.
    Unknown,
    CommonAverage,
    LinkedMastoids,
    Electrode(String),
    Custom(String),
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Electrode {
    /// Original electrode label, e.g. "O1" or "Fp1".
    pub label: String,
}

impl Electrode {
    pub fn new(label: impl Into<String>) -> Result<Self, EegError> {
        let label = label.into();
        if label.trim().is_empty() {
            return Err(EegError::EmptyElectrodeLabel);
        }
        Ok(Self { label })
    }
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct EegChannel {
    /// Original channel label from the source recording.
    pub label: String,
    pub unit: VoltageUnit,
    pub electrode: Option<Electrode>,
    pub reference: ChannelReference,
}

impl EegChannel {
    pub fn new(
        label: impl Into<String>,
        unit: VoltageUnit,
        electrode: Option<Electrode>,
        reference: ChannelReference,
    ) -> Result<Self, EegError> {
        let label = label.into();
        if label.trim().is_empty() {
            return Err(EegError::EmptyChannelLabel);
        }
        Ok(Self { label, unit, electrode, reference })
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum DataOrigin {
    /// Samples measured by an acquisition system.
    Recorded,
    /// Samples generated by an explicitly declared simulation.
    Simulated,
    /// Samples produced by processing another dataset.
    Derived,
}

#[derive(Debug, Clone, PartialEq)]
pub struct Annotation {
    /// Event onset measured from the beginning of this recording, in seconds.
    pub onset_seconds: f64,
    /// Event duration in seconds. Zero is valid for point events.
    pub duration_seconds: f64,
    pub label: String,
}

impl Annotation {
    pub fn new(
        onset_seconds: f64,
        duration_seconds: f64,
        label: impl Into<String>,
    ) -> Result<Self, EegError> {
        let label = label.into();
        if !onset_seconds.is_finite() || onset_seconds < 0.0 {
            return Err(EegError::InvalidAnnotationOnset(onset_seconds));
        }
        if !duration_seconds.is_finite() || duration_seconds < 0.0 {
            return Err(EegError::InvalidAnnotationDuration(duration_seconds));
        }
        if label.trim().is_empty() {
            return Err(EegError::EmptyAnnotationLabel);
        }
        Ok(Self { onset_seconds, duration_seconds, label })
    }
}

#[derive(Debug, Clone, PartialEq)]
pub struct EegRecording {
    pub sampling_rate: SamplingRate,
    pub channels: Vec<EegChannel>,
    /// One vector per channel; samples within each vector are time ordered.
    pub samples_by_channel: Vec<Vec<f64>>,
    pub annotations: Vec<Annotation>,
    pub origin: DataOrigin,
}

impl EegRecording {
    pub fn new(
        sampling_rate: SamplingRate,
        channels: Vec<EegChannel>,
        samples_by_channel: Vec<Vec<f64>>,
        annotations: Vec<Annotation>,
        origin: DataOrigin,
    ) -> Result<Self, EegError> {
        if channels.is_empty() {
            return Err(EegError::NoChannels);
        }
        if samples_by_channel.len() != channels.len() {
            return Err(EegError::ChannelDataCountMismatch {
                channels: channels.len(),
                data_vectors: samples_by_channel.len(),
            });
        }

        let sample_count = samples_by_channel.first().map_or(0, Vec::len);
        if sample_count == 0 {
            return Err(EegError::NoSamples);
        }
        for (index, samples) in samples_by_channel.iter().enumerate() {
            if samples.len() != sample_count {
                return Err(EegError::UnequalChannelLengths {
                    channel_index: index,
                    expected: sample_count,
                    actual: samples.len(),
                });
            }
        }

        let duration = sample_count as f64 / sampling_rate.hz();
        for annotation in &annotations {
            let end = annotation.onset_seconds + annotation.duration_seconds;
            if end > duration {
                return Err(EegError::AnnotationOutsideRecording {
                    end_seconds: end,
                    recording_duration_seconds: duration,
                });
            }
        }

        Ok(Self {
            sampling_rate,
            channels,
            samples_by_channel,
            annotations,
            origin,
        })
    }

    pub fn sample_count(&self) -> usize {
        self.samples_by_channel.first().map_or(0, Vec::len)
    }

    /// Duration implied by the sample count and the common sampling rate.
    pub fn duration_seconds(&self) -> f64 {
        self.sample_count() as f64 / self.sampling_rate.hz()
    }
}

#[derive(Debug, Clone, PartialEq)]
pub enum EegError {
    InvalidSamplingRate(f64),
    EmptyChannelLabel,
    EmptyElectrodeLabel,
    EmptyAnnotationLabel,
    InvalidAnnotationOnset(f64),
    InvalidAnnotationDuration(f64),
    NoChannels,
    NoSamples,
    ChannelDataCountMismatch { channels: usize, data_vectors: usize },
    UnequalChannelLengths { channel_index: usize, expected: usize, actual: usize },
    AnnotationOutsideRecording { end_seconds: f64, recording_duration_seconds: f64 },
}

impl std::fmt::Display for EegError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::InvalidSamplingRate(hz) => write!(f, "sampling rate must be finite and positive, got {hz}"),
            Self::EmptyChannelLabel => write!(f, "channel label cannot be empty"),
            Self::EmptyElectrodeLabel => write!(f, "electrode label cannot be empty"),
            Self::EmptyAnnotationLabel => write!(f, "annotation label cannot be empty"),
            Self::InvalidAnnotationOnset(value) => write!(f, "annotation onset must be finite and non-negative, got {value}"),
            Self::InvalidAnnotationDuration(value) => write!(f, "annotation duration must be finite and non-negative, got {value}"),
            Self::NoChannels => write!(f, "an EEG recording must contain at least one channel"),
            Self::NoSamples => write!(f, "an EEG recording must contain at least one sample per channel"),
            Self::ChannelDataCountMismatch { channels, data_vectors } => write!(f, "{channels} channels were declared but {data_vectors} sample vectors were supplied"),
            Self::UnequalChannelLengths { channel_index, expected, actual } => write!(f, "channel {channel_index} has {actual} samples; expected {expected}"),
            Self::AnnotationOutsideRecording { end_seconds, recording_duration_seconds } => write!(f, "annotation ends at {end_seconds}s, beyond recording duration {recording_duration_seconds}s"),
        }
    }
}

impl std::error::Error for EegError {}

#[cfg(test)]
mod tests {
    use super::*;

    fn channel(label: &str) -> EegChannel {
        EegChannel::new(
            label,
            VoltageUnit::Microvolt,
            Some(Electrode::new(label).unwrap()),
            ChannelReference::Unknown,
        ).unwrap()
    }

    #[test]
    fn builds_a_two_channel_recording_and_computes_duration() {
        let recording = EegRecording::new(
            SamplingRate::new(256.0).unwrap(),
            vec![channel("O1"), channel("O2")],
            vec![vec![1.0; 256], vec![2.0; 256]],
            vec![Annotation::new(0.5, 0.25, "eyes_closed").unwrap()],
            DataOrigin::Recorded,
        ).unwrap();

        assert_eq!(recording.sample_count(), 256);
        assert!((recording.duration_seconds() - 1.0).abs() < 1e-12);
        assert_eq!(recording.origin, DataOrigin::Recorded);
    }

    #[test]
    fn rejects_mismatched_channel_lengths() {
        let result = EegRecording::new(
            SamplingRate::new(256.0).unwrap(),
            vec![channel("O1"), channel("O2")],
            vec![vec![1.0; 10], vec![2.0; 9]],
            vec![],
            DataOrigin::Recorded,
        );
        assert!(matches!(result, Err(EegError::UnequalChannelLengths { .. })));
    }

    #[test]
    fn rejects_annotations_beyond_recording_end() {
        let result = EegRecording::new(
            SamplingRate::new(10.0).unwrap(),
            vec![channel("Cz")],
            vec![vec![0.0; 10]],
            vec![Annotation::new(0.9, 0.2, "event").unwrap()],
            DataOrigin::Recorded,
        );
        assert!(matches!(result, Err(EegError::AnnotationOutsideRecording { .. })));
    }

    #[test]
    fn converts_microvolts_to_volts() {
        assert!((VoltageUnit::Microvolt.to_volts_scale() - 1e-6).abs() < 1e-15);
    }
}
